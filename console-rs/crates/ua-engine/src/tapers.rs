//! Conversions between the engine's tapered (0…1) control values and display units, as specified
//! in `console-port/protocol/ui-to-path.md`.
//!
//! The engine is authoritative: write the tapered value, then show the dB it pushes back. These
//! functions exist for optimistic local display and for gestures that start from a dB value.

/// Input, send and aux faders share one curve: −144 (−∞) … +12 dB.
pub mod fader {
    use super::FADER_LUT;

    /// Tapered value for 0 dB, 43/55 = 0.7818182. The engine's default for every fader.
    pub const UNITY: f64 = 43.0 / 55.0;
    pub const MIN_DB: f64 = -144.0;
    pub const MAX_DB: f64 = 12.0;
    /// Above this the curve is `dB = 55·t − 43` (exact to ±0.1 dB against the captured LUT).
    pub const LINEAR_FROM: f64 = 0.5528;
    const LINEAR_FROM_DB: f64 = 55.0 * LINEAR_FROM - 43.0;

    /// Tapered 0…1 → dB.
    pub fn db_from_tapered(t: f64) -> f64 {
        if t <= 0.0 {
            return MIN_DB;
        }
        if t >= 1.0 {
            return MAX_DB;
        }
        if t >= LINEAR_FROM {
            return 55.0 * t - 43.0;
        }
        let pos = t * 360.0;
        let i = (pos as usize).min(359);
        let frac = pos - i as f64;
        FADER_LUT[i] + frac * (FADER_LUT[i + 1] - FADER_LUT[i])
    }

    /// dB → tapered 0…1.
    pub fn tapered_from_db(db: f64) -> f64 {
        if db <= MIN_DB {
            return 0.0;
        }
        if db >= MAX_DB {
            return 1.0;
        }
        if db >= LINEAR_FROM_DB {
            return (db + 43.0) / 55.0;
        }
        // Binary search the monotonic LUT below the linear section.
        let (mut lo, mut hi) = (0usize, 360usize);
        while lo < hi - 1 {
            let mid = (lo + hi) / 2;
            if FADER_LUT[mid] <= db {
                lo = mid;
            } else {
                hi = mid;
            }
        }
        let span = FADER_LUT[hi] - FADER_LUT[lo];
        let t = if span == 0.0 {
            lo as f64 / 360.0
        } else {
            (lo as f64 + (db - FADER_LUT[lo]) / span) / 360.0
        };
        t.min(LINEAR_FROM)
    }
}

/// Mic preamp (`preamps/0/GainTapered` ↔ `Gain`): `dB = round(10 + 55·t)`, 10…65 dB in integer
/// steps; `t = (dB − 10)/55`. Line-mode range and Unison custom scales (`PreampInputKnobSteps`)
/// are not covered.
pub mod preamp {
    pub const MIN_DB: f64 = 10.0;
    pub const MAX_DB: f64 = 65.0;

    pub fn db_from_tapered(t: f64) -> f64 {
        (MIN_DB + 55.0 * t.clamp(0.0, 1.0)).round()
    }

    pub fn tapered_from_db(db: f64) -> f64 {
        ((db - MIN_DB) / 55.0).clamp(0.0, 1.0)
    }
}

/// Monitor knob (`CRMonitorLevelTapered` ↔ `CRMonitorLevel`): −96 … 0 dB in 0.5 dB steps. The
/// engine's hardware code is `hw = 192 + 2·dB`.
pub mod monitor {
    use super::{MONITOR_FWD, MONITOR_REV};

    pub const MIN_DB: f64 = -96.0;
    pub const MAX_DB: f64 = 0.0;

    /// Tapered 0…1 → dB (a multiple of 0.5).
    pub fn db_from_tapered(t: f64) -> f64 {
        (hw_from_tapered(t) as f64 - 192.0) / 2.0
    }

    /// dB → tapered 0…1 (the midpoint of the tapered range that yields this dB).
    pub fn tapered_from_db(db: f64) -> f64 {
        let hw = (192.0 + 2.0 * db).round() as i64;
        if hw <= 0 {
            return 0.0;
        }
        if hw >= 192 {
            return 1.0;
        }
        MONITOR_REV[hw as usize]
    }

    /// Hardware code 0…192 for a tapered value.
    pub fn hw_from_tapered(t: f64) -> u8 {
        if t <= 0.0 {
            return 0;
        }
        if t >= 1.0 {
            return 192;
        }
        let pos = t * 360.0;
        let i = (pos as usize).min(359);
        let frac = pos - i as f64;
        let a = MONITOR_FWD[i] as f64;
        let v = a + frac * (MONITOR_FWD[i + 1] as f64 - a);
        v.round().clamp(0.0, 192.0) as u8
    }

    /// Every hardware code the knob can produce (the captured sweep).
    pub fn codes() -> &'static [u8] {
        &MONITOR_FWD
    }
}

/// Pan (`Pan`, `Pan2`, send `Pan`) is linear −1 (L100) … 0 (C) … +1 (R100).
pub mod pan {
    /// Pan −1…1 → knob 0…1.
    pub fn knob_from_pan(p: f64) -> f64 {
        (p.clamp(-1.0, 1.0) + 1.0) / 2.0
    }

    /// Knob 0…1 → pan −1…1.
    pub fn pan_from_knob(k: f64) -> f64 {
        k.clamp(0.0, 1.0) * 2.0 - 1.0
    }

    /// Console's readout: `L100` … `C` … `R100`.
    pub fn label(p: f64) -> String {
        let n = (p.abs() * 100.0).round() as i64;
        if n == 0 {
            return "C".to_owned();
        }
        format!("{}{n}", if p < 0.0 { 'L' } else { 'R' })
    }
}

/// Console's fader readout (Rack.dll 0x181bb1294, also aux faders and mini sends): `-∞` below
/// −143.9 dB, otherwise the engine's 32-bit value to one decimal (`%.1f`), with `+` when it is
/// above 0. The sign comes from the value before rounding: −0.01 prints `-0.0`, +0.047 `+0.0`,
/// and only exactly 0 prints `0.0`.
pub fn format_db(db: f64) -> String {
    let v = db as f32;
    // `(double)v < -143.9`; NaN reads as the floor too.
    if !(v as f64 >= -143.9) {
        return "-\u{221e}".to_owned();
    }
    format!("{}{:.1}", if v > 0.0 { "+" } else { "" }, v as f64)
}

/// Console's monitor level readout (Rack.dll 0x1811e8800): `-INF` below −95.9 dB, otherwise
/// `juce::String(v, 1)` + `" dB"` (no `+`).
pub fn format_monitor_db(db: f64) -> String {
    let v = db as f32;
    if !(v as f64 >= -95.9) {
        return "-INF".to_owned();
    }
    format!("{:.1} dB", v as f64)
}

