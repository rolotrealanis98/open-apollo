#!/usr/bin/env python3
"""Generate the per-model ALSA UCM2 profiles from devices/*.json.

Writes into configs/ucm2/ua_apollo/:
  ua_apollo.conf        one If block per model, matching ${CardName}
  HiFi-<model>.conf     one use case per model (channel counts from the JSON)

The Apollo x4 keeps its hand-written HiFi.conf (channel order documented in
it); its If block in ua_apollo.conf is emitted verbatim, so the x4 result is
the same as before this generator existed.  USB models (snd-usb-audio, never
a ua_apollo card) and models without playback routes are skipped.

The channel counts are those of the model's default digital mode
(legacy_digital_mode) at 44.1/48 kHz.  The ALSA channel count of some models
follows the digital mode (S/PDIF vs ADAT); /proc/asound/cardN/io_map is
authoritative.  The card names are the "model" strings of the JSON, which are
the names the driver gives its ALSA cards (ua_device_name()).

Usage:
  tools/gen-ucm2.py            write the files
  tools/gen-ucm2.py --check    exit 1 if the files on disk differ
"""
import glob
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "configs", "ucm2", "ua_apollo")

TYPE_NAMES = ["MIC/LINE/HIZ", "MIC/LINE", "AUX", "LINE", "ADAT", "S/PDIF",
              "AES/EBU", "VIRTUAL", "MADI", "MON", "CUE", "TALKBACK",
              "RESERVED", "DANTE", "UNKNOWN"]

X4_MODEL = "Apollo x4"

HEADER = '''# UCM2 profile for the Universal Audio Apollo family (Thunderbolt, ua_apollo driver)
# GENERATED by tools/gen-ucm2.py from devices/*.json -- do not edit by hand
# (the Apollo x4 use case, HiFi.conf, is hand-written and kept as is).
# Deploy to: /usr/share/alsa/ucm2/ua_apollo/ua_apollo.conf
# Symlink from: /usr/share/alsa/ucm2/conf.d/ua_apollo/ua_apollo.conf
#
# alsa-lib finds this through conf.d/${CardDriver}/${CardDriver}.conf, and every
# Apollo model registers with the card driver name "ua_apollo".  The use case
# is chosen by the card name (the model name the driver gives its ALSA card);
# each model has its own channel counts.  A card whose name is not listed
# gets no UCM profile rather than a wrongly labelled one.

Syntax 6
'''

X4_BLOCK = '''
If.apollo_x4 {
	Condition {
		Type String
		String1 "${CardName}"
		String2 "Apollo x4"
	}
	True {
		SectionUseCase."HiFi" {
			File "HiFi.conf"
			Comment "Apollo x4: 24 playback / 22 capture channels (firmware IO layout)"
		}
	}
}
'''

BLOCK = '''
If.{ident} {{
	Condition {{
		Type String
		String1 "${{CardName}}"
		String2 "{model}"
	}}
	True {{
		SectionUseCase."HiFi" {{
			File "HiFi-{slug}.conf"
			Comment "{model}: {play} playback / {rec} capture channels"
		}}
	}}
}}
'''

HIFI = '''# UCM2 HiFi use case for the Universal Audio {model}
# GENERATED by tools/gen-ucm2.py from devices/{jsonfile} -- do not edit by hand.
#
# Channel counts are those of the default digital mode ({mode}) at 44.1/48 kHz.
# Route table of that mode, by channel type:
#   playback: {play_types}
#   capture:  {rec_types}
# The channel order and the digital-mode dependent channels are decided by the
# firmware; /proc/asound/cardN/io_map is authoritative, not this file.
#
# This profile deliberately does not touch hardware state:
#   - no sample rate, format or period/buffer is pinned, so the application,
#     PipeWire or the clock source decides;
#   - no ALSA controls are written.  Monitor, Dim, Mono, preamp, clock and
#     digital-mode controls are hardware state owned by the user and the
#     mixer daemon, and a UCM "cset" would reset them on every device enable.

SectionVerb {{
	EnableSequence [
	]
	DisableSequence [
	]

	Value {{
		PlaybackPCM "hw:${{CardId}}"
		CapturePCM "hw:${{CardId}}"
	}}
}}

SectionDevice."Outputs" {{
	Comment "{model} playback ({play} channels)"

	EnableSequence [
	]
	DisableSequence [
	]

	Value {{
		PlaybackPriority 200
		PlaybackPCM "hw:${{CardId}}"
		PlaybackChannels {play}
	}}
}}

SectionDevice."Inputs" {{
	Comment "{model} capture ({rec} channels)"

	EnableSequence [
	]
	DisableSequence [
	]

	Value {{
		CapturePriority 200
		CapturePCM "hw:${{CardId}}"
		CaptureChannels {rec}
	}}
}}
'''


def route_ids(d, direction, mode):
    ids = [int(r["ch_id"], 16) for r in d["routes"]["LoMid"][direction]]
    drop = None
    if d.get("digital_io") not in ("aes", "madi"):
        drop = 5 if mode == "adat" else 4   # S/PDIF in ADAT mode, ADAT in S/PDIF mode
    return [i for i in ids if drop is None or (i >> 8) != drop]


def type_summary(ids):
    order, count = [], {}
    for i in ids:
        t = min(i >> 8, 14)
        if t not in count:
            order.append(t)
        count[t] = count.get(t, 0) + 1
    return ", ".join("%s x%d" % (TYPE_NAMES[t], count[t]) for t in order) or "none"


def models():
    out = []
    for path in sorted(glob.glob(os.path.join(ROOT, "devices", "*.json"))):
        base = os.path.basename(path)
        if "usb" in base:
            continue
        d = json.load(open(path))
        if "routes" not in d or "channel_counts" not in d:
            continue
        mode = d.get("legacy_digital_mode", "spdif")
        counts = d["channel_counts"]["LoMid"][mode]
        if not counts["playback"] or not counts["record"]:
            continue
        out.append((base, d, mode, counts))
    return out


def generate():
    files = {}
    conf = HEADER
    for base, d, mode, counts in models():
        slug = base[len("apollo-"):-5] if base.startswith("apollo-") else base[:-5]
        if d["model"] == X4_MODEL:
            conf += X4_BLOCK
            continue
        ident = "apollo_" + slug.replace("-", "_")
        play, rec = counts["playback"], counts["record"]
        conf += BLOCK.format(ident=ident, model=d["model"], slug=slug, play=play, rec=rec)
        files["HiFi-%s.conf" % slug] = HIFI.format(
            model=d["model"], jsonfile=base, mode="ADAT" if mode == "adat" else "S/PDIF",
            play=play, rec=rec,
            play_types=type_summary(route_ids(d, "playback", mode)),
            rec_types=type_summary(route_ids(d, "record", mode)))
    files["ua_apollo.conf"] = conf
    return files


def main():
    files = generate()
    check = "--check" in sys.argv[1:]
    bad = 0
    for name, text in sorted(files.items()):
        path = os.path.join(OUT, name)
        old = open(path).read() if os.path.exists(path) else None
        if check:
            if old != text:
                print("out of date: %s" % path)
                bad = 1
        else:
            if old != text:
                open(path, "w").write(text)
                print("wrote %s" % path)
    sys.exit(bad)


if __name__ == "__main__":
    main()
